-- 1. TABELA DE CATEGORIAS DE DESAFIOS
CREATE TABLE CP_CATEGORIAS_DESAFIO (
    CATEGORIA_ID   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME           VARCHAR2(50) NOT NULL,
    DESCRICAO      VARCHAR2(200),
    ICONE_URL      VARCHAR2(500)
);

-- 2. TABELA DE LIGAS (Bronze, Prata, Ouro, etc.)
CREATE TABLE CP_LIGAS (
    LIGA_ID        NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME           VARCHAR2(50) NOT NULL UNIQUE,
    PONTOS_MINIMO  NUMBER(10) NOT NULL,
    PONTOS_MAXIMO  NUMBER(10) NOT NULL,
    COR_HEX        VARCHAR2(7),
    ICONE_URL      VARCHAR2(500)
);

-- 3. TABELA DE USUÁRIOS
CREATE TABLE CP_USERS (
    USER_ID        NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME           VARCHAR2(100) NOT NULL,
    EMAIL          VARCHAR2(150) NOT NULL UNIQUE,
    SENHA_HASH     VARCHAR2(255) NOT NULL,
    FOTO_URL       VARCHAR2(500),
    BIO            VARCHAR2(300),
    PONTOS         NUMBER(10) DEFAULT 0 NOT NULL,
    CRIADO_EM      DATE DEFAULT SYSDATE NOT NULL,
    ATIVO          NUMBER(1) DEFAULT 1 NOT NULL
);

-- 4. TABELA DE DESAFIOS
CREATE TABLE CP_DESAFIOS (
    DESAFIO_ID     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITULO         VARCHAR2(150) NOT NULL,
    DESCRICAO      VARCHAR2(500),
    META_VALOR     NUMBER(10,2) NOT NULL,
    META_UNIDADE   VARCHAR2(20) NOT NULL,
    PONTOS_RECOM   NUMBER(10) NOT NULL,
    DURACAO_DIAS   NUMBER(5) DEFAULT 1,
    NIVEL          VARCHAR2(20) DEFAULT 'FACIL',
    ATIVO          NUMBER(1) DEFAULT 1,
    CATEGORIA_ID   NUMBER(10) NOT NULL,
    CONSTRAINT FK_DESAFIO_CATEGORIA FOREIGN KEY (CATEGORIA_ID) REFERENCES CP_CATEGORIAS_DESAFIO(CATEGORIA_ID)
);

-- 5. TABELA DE USER_DESAFIOS (progresso do usuário em desafios)
CREATE TABLE CP_USER_DESAFIOS (
    USER_DESAFIO_ID NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID         NUMBER(10) NOT NULL,
    DESAFIO_ID      NUMBER(10) NOT NULL,
    INICIADO_EM     DATE DEFAULT SYSDATE NOT NULL,
    CONCLUIDO_EM    DATE,
    PROGRESSO_ATUAL NUMBER(10,2) DEFAULT 0,
    STATUS          VARCHAR2(20) DEFAULT 'EM_ANDAMENTO',
    PONTOS_GANHOS   NUMBER(10) DEFAULT 0,
    CONSTRAINT FK_UD_USER     FOREIGN KEY (USER_ID)    REFERENCES CP_USERS(USER_ID),
    CONSTRAINT FK_UD_DESAFIO  FOREIGN KEY (DESAFIO_ID) REFERENCES CP_DESAFIOS(DESAFIO_ID),
    CONSTRAINT CHK_UD_STATUS  CHECK (STATUS IN ('EM_ANDAMENTO', 'CONCLUIDO', 'ABANDONADO'))
);

-- 6. TABELA DE POSTS (feed social)
CREATE TABLE CP_POSTS (
    POST_ID        NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID        NUMBER(10) NOT NULL,
    CONTEUDO       VARCHAR2(1000) NOT NULL,
    MIDIA_URL      VARCHAR2(500),
    TIPO_MIDIA     VARCHAR2(10),
    DESAFIO_REF    NUMBER(10),
    CRIADO_EM      DATE DEFAULT SYSDATE NOT NULL,
    ATIVO          NUMBER(1) DEFAULT 1,
    CONSTRAINT FK_POST_USER FOREIGN KEY (USER_ID) REFERENCES CP_USERS(USER_ID),
    CONSTRAINT FK_POST_DESAFIO FOREIGN KEY (DESAFIO_REF) REFERENCES CP_DESAFIOS(DESAFIO_ID)
);

-- 7. TABELA DE CURTIDAS
CREATE TABLE CP_CURTIDAS (
    CURTIDA_ID     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    POST_ID        NUMBER(10) NOT NULL,
    USER_ID        NUMBER(10) NOT NULL,
    CRIADO_EM      DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_CURTIDA_POST FOREIGN KEY (POST_ID) REFERENCES CP_POSTS(POST_ID),
    CONSTRAINT FK_CURTIDA_USER FOREIGN KEY (USER_ID) REFERENCES CP_USERS(USER_ID),
    CONSTRAINT UK_CURTIDA UNIQUE (POST_ID, USER_ID)   -- evita curtida duplicada
);

-- 8. TABELA DE COMENTÁRIOS
CREATE TABLE CP_COMENTARIOS (
    COMENTARIO_ID  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    POST_ID        NUMBER(10) NOT NULL,
    USER_ID        NUMBER(10) NOT NULL,
    CONTEUDO       VARCHAR2(500) NOT NULL,
    CRIADO_EM      DATE DEFAULT SYSDATE NOT NULL,
    ATIVO          NUMBER(1) DEFAULT 1,
    CONSTRAINT FK_COMENTARIO_POST FOREIGN KEY (POST_ID) REFERENCES CP_POSTS(POST_ID),
    CONSTRAINT FK_COMENTARIO_USER FOREIGN KEY (USER_ID) REFERENCES CP_USERS(USER_ID)
);

-- 9. TABELA DE CONEXÕES (solicitações/amizades)
CREATE TABLE CP_CONEXOES (
    CONEXAO_ID     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SOLICITANTE_ID NUMBER(10) NOT NULL,
    RECEPTOR_ID    NUMBER(10) NOT NULL,
    STATUS         VARCHAR2(20) DEFAULT 'PENDENTE',
    CRIADO_EM      DATE DEFAULT SYSDATE NOT NULL,
    ATUALIZADO_EM  DATE,
    CONSTRAINT FK_CONEX_SOLICITANTE FOREIGN KEY (SOLICITANTE_ID) REFERENCES CP_USERS(USER_ID),
    CONSTRAINT FK_CONEX_RECEPTOR    FOREIGN KEY (RECEPTOR_ID)    REFERENCES CP_USERS(USER_ID),
    CONSTRAINT CHK_CONEX_STATUS CHECK (STATUS IN ('PENDENTE', 'ACEITO', 'RECUSADO')),
    CONSTRAINT UK_CONEXAO UNIQUE (SOLICITANTE_ID, RECEPTOR_ID)   -- evita duplicidade
);

-- 10. TABELA DE HISTÓRICO DE PONTOS
CREATE TABLE CP_HISTORICO_PONTOS (
    HISTORICO_ID   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID        NUMBER(10) NOT NULL,
    PONTOS         NUMBER(10) NOT NULL,
    MOTIVO         VARCHAR2(200) NOT NULL,
    ORIGEM_TIPO    VARCHAR2(30),
    ORIGEM_ID      NUMBER(10),
    CRIADO_EM      DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_HIST_USER FOREIGN KEY (USER_ID) REFERENCES CP_USERS(USER_ID)
);

